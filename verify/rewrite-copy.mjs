/**
 * 文案重写：短句、具体、不排比、不升华。
 *
 * 去掉了三类 AI 痕迹：
 *  1. 「以后…以后…以后…以后…」的四连排比 —— 换成句子结构各不相同
 *  2. 「活成谁的标准答案」「不用解释的特权」这类抽象升华
 *  3. 「像歌里唱的那样，把每一天都过成自己的生日」这种把歌词再解释一遍的收尾
 * 留下的是能验证的真话：她知道的事、我会做的事、我做不到的事。
 */
import { readFileSync, writeFileSync } from 'node:fs'

const F = 'src/site.config.ts'
let s = readFileSync(F, 'utf8')
let miss = 0
const rep = (from, to) => {
  if (!s.includes(from)) {
    console.log('MISS: ' + from.split('\n')[0].slice(0, 60))
    miss++
    return
  }
  s = s.replace(from, to)
  console.log('OK  : ' + from.split('\n')[0].slice(0, 60))
}

